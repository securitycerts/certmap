// Wording of the comparison pages in every language they are published in.
//
// A comparison is assembled from the two dataset rows, so each language needs
// the same small set of labels and sentences. The sentences are built so that
// a certification's acronym never has to be inflected: it always stands on its
// own or after a fixed noun ("the X exam"), which keeps the grammar right in
// languages with articles, cases or particles. Numbers, prices and durations
// are formatted by Intl for the locale.

const FSI = "⁨", PDI = "⁩";

function make(code, { locale, dir = "ltr", name, levels, t }) {
  // In right-to-left text a Latin acronym or a price is isolated so the
  // punctuation around it stays where it was typed.
  const iso = s => (dir === "rtl" ? FSI + s + PDI : String(s));
  const money = n => iso(new Intl.NumberFormat(locale + "-u-nu-latn", { style: "currency", currency: "USD", maximumFractionDigits: 0 }).format(n));
  const unit = (n, u) => new Intl.NumberFormat(locale + "-u-nu-latn", { style: "unit", unit: u, unitDisplay: "long" }).format(n);
  const duration = min => {
    if (!min) return null;
    if (min < 600) return unit(min, "minute");
    const hours = min / 60;
    return hours % 24 === 0 && hours >= 48 ? unit(hours / 24, "day") : unit(hours, "hour");
  };
  return { code, locale, dir, name, levels, iso, money, duration, ...t };
}

